// Helper to generate a calibrated 128D visual embedding for catalog items
function createProductVector(
  rgb: [number, number, number],
  brightness: number,
  saturation: number,
  edgeDensity: number,
  categoryIndex: number
): number[] {
  const vec = new Float32Array(128);

  // 1. Color histogram (64 dims)
  const rBin = Math.min(3, Math.floor(rgb[0] / 64));
  const gBin = Math.min(3, Math.floor(rgb[1] / 64));
  const bBin = Math.min(3, Math.floor(rgb[2] / 64));
  const mainBin = rBin * 16 + gBin * 4 + bBin;

  vec[mainBin] = 0.65;
  if (mainBin > 0) vec[mainBin - 1] = 0.15;
  if (mainBin < 63) vec[mainBin + 1] = 0.15;

  // 2. Spatial / edge moments (32 dims: 64..95)
  for (let i = 0; i < 32; i++) {
    const isEdge = i % 2 === 1;
    vec[64 + i] = isEdge ? edgeDensity * (0.8 + 0.4 * Math.sin(i)) : brightness * (0.7 + 0.3 * Math.cos(i));
  }

  // 3. Centroids (16 dims: 96..111)
  vec[96] = rgb[0] / 255;
  vec[97] = rgb[1] / 255;
  vec[98] = rgb[2] / 255;
  vec[99] = 0.75;

  vec[100] = (rgb[0] * 0.8) / 255;
  vec[101] = (rgb[1] * 0.8) / 255;
  vec[102] = (rgb[2] * 0.8) / 255;
  vec[103] = 0.25;

  // 4. Global statistics (16 dims: 112..127)
  vec[112] = brightness;
  vec[113] = saturation;
  vec[114] = 0.5;
  vec[115] = edgeDensity;
  vec[116] = rgb[0] / 255;
  vec[117] = rgb[1] / 255;
  vec[118] = rgb[2] / 255;
  vec[119] = categoryIndex / 10;
  vec[120] = (categoryIndex * 2) / 10;

  // L2 normalize
  let normSq = 0;
  for (let i = 0; i < 128; i++) {
    normSq += vec[i] * vec[i];
  }
  const norm = Math.sqrt(normSq) || 1.0;
  const res: number[] = new Array(128);
  for (let i = 0; i < 128; i++) {
    res[i] = Number((vec[i] / norm).toFixed(6));
  }
  return res;
}

